"""
app/pages/2_Dataset_Overview.py
==================================
Dataset Overview page: summarizes the cleaned/engineered dataset, shows the
target class distribution, feature statistics, a sample of records, and
reuses the EDA figures already generated by
`03_Exploratory_Data_Analysis.ipynb`. Large CSVs are read with a row cap so
this page stays responsive even against the full 2M+ row dataset.
"""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd
import streamlit as st

from src.config.settings import FEATURED_DATA_PATH, TARGET_COLUMN
from src.utils.io_helpers import load_csv_safe
from src.utils.ui_helpers import configure_page, render_missing_artifact_notice, render_sidebar_branding
from src.visualization.charts import build_target_distribution_chart
from src.visualization.report_loader import (
    get_data_dictionary,
    get_dataset_report_markdown,
    list_figures,
)
from src.config.settings import EDA_FIGURES_DIR

configure_page(page_title="Dataset Overview", page_icon="📊")
render_sidebar_branding()

st.title("📊 Dataset Overview")
st.markdown(
    "A summary of the cleaned, feature-engineered dataset that trains the "
    "production model — reused directly from the project's data and EDA notebooks."
)

# Row cap keeps this page responsive even against the full multi-million-row
# dataset; every statistic below is clearly labeled as sample-based.
SAMPLE_ROW_LIMIT = 20_000


@st.cache_data(show_spinner="Loading dataset sample...")
def _load_dataset_sample(row_limit: int) -> pd.DataFrame | None:
    return load_csv_safe(FEATURED_DATA_PATH, nrows=row_limit)


dataset_sample = _load_dataset_sample(SAMPLE_ROW_LIMIT)

if dataset_sample is None:
    render_missing_artifact_notice(
        "The engineered dataset", "04_Feature_Engineering.ipynb"
    )
else:
    st.caption(
        f"Statistics below are computed from the first {len(dataset_sample):,} rows "
        f"of `Dataset/processed/featured_accident_data.csv` (loaded with a row cap "
        f"for responsiveness in this app)."
    )

    # ---- Dataset Summary ----
    st.markdown("## Dataset Summary")
    summary_cols = st.columns(4)
    summary_cols[0].metric("Rows Loaded", f"{len(dataset_sample):,}")
    summary_cols[1].metric("Columns", f"{dataset_sample.shape[1]}")
    summary_cols[2].metric(
        "Missing Values", f"{int(dataset_sample.isnull().sum().sum()):,}"
    )
    memory_mb = dataset_sample.memory_usage(deep=True).sum() / (1024 ** 2)
    summary_cols[3].metric("Memory (Sample)", f"{memory_mb:.1f} MB")

    # ---- Target Distribution ----
    st.markdown("## Target Distribution")
    if TARGET_COLUMN in dataset_sample.columns:
        target_counts = dataset_sample[TARGET_COLUMN].value_counts()
        st.plotly_chart(build_target_distribution_chart(target_counts), use_container_width=True)
    else:
        st.warning(f"Target column '{TARGET_COLUMN}' not found in the loaded sample.")

    # ---- Feature Statistics ----
    st.markdown("## Feature Statistics")
    numeric_columns = dataset_sample.select_dtypes(include="number").columns.tolist()
    if numeric_columns:
        st.dataframe(dataset_sample[numeric_columns].describe().T, use_container_width=True)
    else:
        st.info("No numeric columns found in the loaded sample.")

    # ---- Sample Data ----
    st.markdown("## Sample Records")
    st.dataframe(dataset_sample.head(50), use_container_width=True)

# ---- Data Dictionary (Phase 2) ----
st.markdown("## Data Dictionary")
data_dictionary = get_data_dictionary()
if data_dictionary is not None:
    st.dataframe(data_dictionary, use_container_width=True)
else:
    render_missing_artifact_notice("The data dictionary", "01_Data_Understanding.ipynb")

# ---- Dataset Report (Phase 2) ----
with st.expander("📄 Full Dataset Report (from Phase 2)"):
    dataset_report = get_dataset_report_markdown()
    if dataset_report is not None:
        st.markdown(dataset_report)
    else:
        render_missing_artifact_notice("The dataset report", "01_Data_Understanding.ipynb")

# ---- EDA Visualizations (Phase 4, reused as-is) ----
st.markdown("## Exploratory Data Analysis Visualizations")
eda_figures = list_figures(EDA_FIGURES_DIR)
if eda_figures:
    st.caption(f"Showing {len(eda_figures)} figure(s) generated by `03_Exploratory_Data_Analysis.ipynb`.")
    figure_columns = st.columns(2)
    for i, figure_path in enumerate(eda_figures):
        with figure_columns[i % 2]:
            st.image(str(figure_path), caption=figure_path.stem.replace("_", " ").title(), use_container_width=True)
else:
    render_missing_artifact_notice("EDA visualizations", "03_Exploratory_Data_Analysis.ipynb")
