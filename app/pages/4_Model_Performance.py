"""
app/pages/4_Model_Performance.py
===================================
Model Performance page: reuses the comparison tables and figures already
generated by Phases 7-9 (`06_Model_Training_and_Comparison.ipynb`,
`07_Hyperparameter_Tuning.ipynb`, `08_Final_Model_Validation_and_
Explainability.ipynb`). Nothing here is recomputed except the optional
ROC/PR curves, which are generated on demand only if the test set and
production model are both available, and are cached for the session.
"""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st

from src.config.settings import TARGET_COLUMN, X_TEST_PATH, Y_TEST_PATH
from src.models.model_loader import ModelLoadError, load_production_model
from src.utils.io_helpers import load_csv_safe
from src.utils.ui_helpers import configure_page, render_metric_card, render_missing_artifact_notice, render_sidebar_branding
from src.visualization.charts import build_precision_recall_curves, build_roc_curves
from src.visualization.report_loader import (
    get_final_metrics,
    get_final_validation_figure,
    get_hyperparameter_tuning_figure,
    get_tuned_model_results,
    list_figures,
)
from src.config.settings import MODEL_COMPARISON_FIGURES_DIR

configure_page(page_title="Model Performance", page_icon="📈")
render_sidebar_branding()

st.title("📈 Model Performance")
st.markdown(
    "Performance of the production model, reused directly from the training, "
    "tuning, and final validation notebooks — nothing on this page is recomputed."
)

# ---- Headline Final Metrics (Phase 9) ----
st.markdown("## Final Model Metrics")
final_metrics = get_final_metrics()
if final_metrics is not None and not final_metrics.empty:
    metrics_row = final_metrics.iloc[0]
    metric_cols = st.columns(5)
    render_metric_card("Accuracy", f"{float(metrics_row['Accuracy']):.1%}", metric_cols[0])
    render_metric_card("Precision", f"{float(metrics_row['Precision (weighted)']):.1%}", metric_cols[1])
    render_metric_card("Recall", f"{float(metrics_row['Recall (weighted)']):.1%}", metric_cols[2])
    render_metric_card("Weighted F1", f"{float(metrics_row['Weighted F1 Score']):.1%}", metric_cols[3])
    render_metric_card("Balanced Accuracy", f"{float(metrics_row['Balanced Accuracy']):.1%}", metric_cols[4])
else:
    render_missing_artifact_notice(
        "Final model metrics", "08_Final_Model_Validation_and_Explainability.ipynb"
    )

# ---- Confusion Matrix (Phase 9) ----
st.markdown("## Confusion Matrix")
confusion_matrix_figure = get_final_validation_figure("confusion_matrix_final_model.png")
if confusion_matrix_figure is not None:
    st.image(str(confusion_matrix_figure), use_container_width=True)
else:
    render_missing_artifact_notice(
        "The final confusion matrix", "08_Final_Model_Validation_and_Explainability.ipynb"
    )

# ---- ROC / Precision-Recall Curves (computed on demand) ----
st.markdown("## ROC and Precision-Recall Curves")
st.caption(
    "Computed on demand (not pre-generated by any notebook) — requires the "
    "test set and production model to both be available."
)


@st.cache_resource(show_spinner=False)
def _load_model_for_curves():
    try:
        return load_production_model()
    except ModelLoadError:
        return None


@st.cache_data(show_spinner="Computing ROC / Precision-Recall curves...")
def _compute_curve_data():
    X_test = load_csv_safe(X_TEST_PATH)
    y_test_df = load_csv_safe(Y_TEST_PATH)
    if X_test is None or y_test_df is None or TARGET_COLUMN not in y_test_df.columns:
        return None, None
    return X_test, y_test_df[TARGET_COLUMN]


curve_model = _load_model_for_curves()
X_test_curves, y_test_curves = _compute_curve_data()

if curve_model is not None and X_test_curves is not None and y_test_curves is not None:
    class_labels_for_curves = sorted(y_test_curves.unique().tolist())
    roc_col, pr_col = st.columns(2)
    with roc_col:
        roc_figure = build_roc_curves(curve_model, X_test_curves, y_test_curves, class_labels_for_curves)
        if roc_figure is not None:
            st.plotly_chart(roc_figure, use_container_width=True)
    with pr_col:
        pr_figure = build_precision_recall_curves(curve_model, X_test_curves, y_test_curves, class_labels_for_curves)
        if pr_figure is not None:
            st.plotly_chart(pr_figure, use_container_width=True)
else:
    st.info(
        "ℹ️ ROC/PR curves are not available — this requires both the production "
        "model (`models/trained/best_gradient_boosting.pkl`) and the test set "
        "(`Dataset/processed/ml_ready/X_test.csv`, `y_test.csv`) to be present."
    )

# ---- Baseline Model Comparison (Phase 7) ----
st.markdown("## Baseline Model Comparison")
baseline_figures = list_figures(MODEL_COMPARISON_FIGURES_DIR)
if baseline_figures:
    st.caption("Figures generated by `06_Model_Training_and_Comparison.ipynb`.")
    figure_columns = st.columns(2)
    for i, figure_path in enumerate(baseline_figures):
        with figure_columns[i % 2]:
            st.image(str(figure_path), caption=figure_path.stem.replace("_", " ").title(), use_container_width=True)
else:
    render_missing_artifact_notice("Baseline model comparison figures", "06_Model_Training_and_Comparison.ipynb")

# ---- Hyperparameter Tuning Comparison (Phase 8) ----
st.markdown("## Hyperparameter Tuning: Baseline vs. Sample-Tuned vs. Final")
tuned_results = get_tuned_model_results()
if tuned_results is not None:
    st.dataframe(tuned_results, use_container_width=True)
else:
    render_missing_artifact_notice("The tuning comparison table", "07_Hyperparameter_Tuning.ipynb")

tuning_comparison_figures = [
    "baseline_vs_tuned_accuracy.png",
    "baseline_vs_tuned_precision.png",
    "baseline_vs_tuned_recall.png",
    "baseline_vs_tuned_f1_score.png",
    "baseline_vs_tuned_balanced_accuracy.png",
]
found_tuning_figures = [
    get_hyperparameter_tuning_figure(name) for name in tuning_comparison_figures
]
found_tuning_figures = [f for f in found_tuning_figures if f is not None]

if found_tuning_figures:
    figure_columns = st.columns(2)
    for i, figure_path in enumerate(found_tuning_figures):
        with figure_columns[i % 2]:
            st.image(str(figure_path), caption=figure_path.stem.replace("_", " ").title(), use_container_width=True)
else:
    render_missing_artifact_notice("Hyperparameter tuning comparison figures", "07_Hyperparameter_Tuning.ipynb")
